# 「這張票合併後還有步驟嗎」的唯一判法。用 source 讀進來，不單獨執行。
#
# 用到它的地方都 source 這一檔，不另寫一份 pattern：
#   - scripts/pr-risk.sh：有 → 這張票在 PR 內文寫 Refs，沒有 → Closes
#   - 開票自檢的「合併時會自動關票」那一格：有、而且有開著的 PR 會關它 → NG
# 兩邊各寫一份，改了一邊另一邊不會跟著改，而且不報錯。
#
# 判準刻意寬：內文任何地方出現「合併後」「部署後」就算有。寬的代價是多寫一張 Refs、
# 合併後由人關票；窄的代價是票在步驟還沒做時就被自動關掉，步驟只剩在一張已關的票上。
#
# 用 bash 的 [[ =~ ]] 比對，不接 grep -q：內文大時，grep -q 先離開會讓上游吃 SIGPIPE，
# 在 pipefail 下整條算失敗，看起來跟「沒有」一模一樣。

AFTER_MERGE_STEP_ERE='(合併|部署)後'

# 參數：票內文。有合併後／部署後的步驟 → 0，沒有 → 1。
has_after_merge_step() {
  [[ "$1" =~ ${AFTER_MERGE_STEP_ERE} ]]
}
